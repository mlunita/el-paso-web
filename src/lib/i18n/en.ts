type WidenStrings<T> = T extends (...args: infer Args) => infer Return
  ? (...args: Args) => Return
  : T extends string
    ? string
    : T extends number
      ? number
      : T extends boolean
        ? boolean
        : T extends Array<infer Item>
          ? WidenStrings<Item>[]
          : T extends object
            ? { [Key in keyof T]: WidenStrings<T[Key]> }
            : T;

export type Strings = WidenStrings<typeof en>;
